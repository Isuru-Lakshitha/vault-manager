import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{
 await page.route('https://api.frankfurter.dev/**',route=>route.fulfill({json:[{base:'LKR',quote:'USD',rate:0.003,date:'2026-10-21'}]}));
 await page.goto('/test/browser/index.html');
 await expect(page.getByRole('heading',{name:'Accounts',exact:true})).toBeVisible();
});
test('card payment, reversal and audit filter preserve ledger',async({page})=>{
 await page.getByRole('link',{name:'Cards',exact:true}).click();
 await page.getByRole('button',{name:'Pay Full',exact:true}).click();
 const payment=page.getByRole('dialog');
 await payment.getByLabel('Payment amount').fill('25');
 await payment.getByRole('combobox').selectOption('bank');
 await payment.getByRole('button',{name:/^Pay /}).click();
 await expect(payment).toBeHidden();
 await page.getByRole('link',{name:'Transactions',exact:true}).click();
 await page.getByText('Payment to Test Visa',{exact:true}).filter({visible:true}).last().click();
 const detail=page.getByRole('dialog');
 await detail.getByPlaceholder('Why is this payment being reversed?').fill('Browser test correction');
 await detail.getByRole('button',{name:'Reverse payment',exact:true}).click();
 await expect(detail).toBeHidden();
 await page.locator('summary').filter({hasText:'Filters & sorting'}).click();
 await page.getByLabel('Audit status').selectOption('Reversed');
 await expect(page.getByText('Payment to Test Visa',{exact:true}).filter({visible:true}).first()).toBeVisible();
 await page.getByRole('link',{name:'Accounts',exact:true}).click();
 await page.getByRole('button',{name:'Reconcile ledger',exact:true}).click();
 const bank=page.getByRole('row').filter({hasText:'Test Bank'});
 await expect(bank.getByRole('cell').nth(2)).toContainText('1,000.00');
 await expect(bank.getByRole('cell').nth(3)).toContainText('1,000.00');
 await expect(bank.getByRole('cell').nth(4)).toContainText('0.00');
 await expect(page.getByText('💳 SPENDING BY ACCOUNT (ALL TIME)',{exact:true})).toBeHidden();
});
test('offline draft synchronizes once and reconciles',async({page,context})=>{
 await page.getByRole('button',{name:'Quick Add',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByLabel('Transaction amount').fill('10');
 await context.setOffline(true);
 await dialog.getByRole('button',{name:'+ Save Transaction',exact:true}).click();
 await expect(page.getByText(/1 payment draft\(s\)/)).toBeVisible();
 await context.setOffline(false);
 await page.getByRole('button',{name:'Sync drafts',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sync drafts',exact:true})).toBeHidden();
 await page.getByRole('button',{name:'Reconcile ledger',exact:true}).click();
 await expect(page.getByRole('row').filter({hasText:'Test Bank'})).toContainText('990.00');
});
test('backup preview blocks invalid references and skips completed restore',async({page})=>{
 await page.getByRole('link',{name:'Settings',exact:true}).click();
 await page.locator('summary').filter({hasText:'Backup & data management'}).click();
 const upload=page.locator('#import-backup-input');
 const invalid={version:2,accounts:[],transactions:[{id:'bad',type:'Expense',amount:10,from_account_id:'missing'}]};
 await upload.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))});
 await expect(page.getByRole('alert')).toContainText('missing accounts reference');
 await expect(page.getByRole('button',{name:'Import backup',exact:true})).toBeDisabled();
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 const valid={version:2,accounts:[{id:'restored',uid:'old-user',name:'Imported Cash',type:'Cash',balance:50,opening_balance:50,currency:'LKR'}]};
 const file={name:'valid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(valid))};
 await upload.setInputFiles(file);
 await expect(page.getByRole('dialog').getByRole('row').filter({hasText:'accounts'})).toContainText('1');
 await page.getByRole('button',{name:'Import backup',exact:true}).click();
 await expect(page.getByText('Data imported successfully!',{exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toBeHidden();
 await upload.setInputFiles(file);
 const cells=page.getByRole('dialog').getByRole('row').filter({hasText:'accounts'}).getByRole('cell');
 await expect(cells.nth(2)).toHaveText('1');
 await expect(cells.nth(3)).toHaveText('0');
});

