test('legacy opening balance setup leaves the current balance unchanged',async({page})=>{
 await page.getByRole('button',{name:'Reconcile ledger',exact:true}).click();
 await page.getByRole('row').filter({hasText:'Legacy Account'}).getByRole('button',{name:'Set opening balance',exact:true}).click();
 await page.getByLabel('Verified opening balance',{exact:true}).fill('500');
 await page.getByRole('button',{name:'Save opening balance',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 const cells=page.getByRole('row').filter({hasText:'Legacy Account'}).getByRole('cell');
 await expect(cells.nth(2)).toContainText('500.00');
 await expect(cells.nth(3)).toContainText('500.00');
 await expect(cells.nth(4)).toContainText('0.00');
});
